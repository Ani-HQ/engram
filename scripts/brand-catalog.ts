#!/usr/bin/env bun
// Regenerates the brand catalog from web/vendor/brands/manifest.json:
//   web/brand-catalog.js                       ids -> local file + tone, used by tooling.js
//   web/vendor/brands/catalog-sources.json      provenance + sha256 of every vendored mark
// After replacing or adding a logo file, update manifest.json and run
// `bun scripts/brand-catalog.ts`. Tests verify the hashes and SVG safety.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../web/vendor/brands/", import.meta.url);
type Entry = { file: string; tone: "color" | "mono"; label: string; source: string; license: string };
const manifest = JSON.parse(readFileSync(new URL("manifest.json", dir), "utf8")) as { brands: Record<string, Entry> };
const ids = Object.keys(manifest.brands).sort();

const assets = ids.map(id => {
  const entry = manifest.brands[id];
  if (!/^[a-z0-9-]+$/.test(id) || !/^[a-z0-9-]+\.(svg|png)$/.test(entry.file) || !["color", "mono"].includes(entry.tone)) throw new Error(`invalid manifest entry: ${id}`);
  const bytes = readFileSync(new URL(entry.file, dir));
  return { id, file: entry.file, tone: entry.tone, label: entry.label, source: entry.source, license: entry.license, sha256: createHash("sha256").update(bytes).digest("hex") };
});
writeFileSync(new URL("catalog-sources.json", dir), JSON.stringify({ format: 2, generated: "scripts/brand-catalog.ts", assets }, null, 2) + "\n");

const catalog = Object.fromEntries(assets.map(({ id, file, tone, label }) => [id, { file, tone, label }]));
writeFileSync(new URL("../web/brand-catalog.js", import.meta.url), `// Generated by scripts/brand-catalog.ts from web/vendor/brands/manifest.json. Do not edit.
// Local product marks only; see web/vendor/brands/SOURCE.md for sources and licenses.
export const brandCatalog = Object.freeze(${JSON.stringify(catalog, null, 2).replace(/\n/g, "\n")});
`);
console.log(`Catalog: ${assets.length} marks.`);
