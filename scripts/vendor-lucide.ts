#!/usr/bin/env bun
// Vendors the Lucide icon subset the interface uses, from one pinned lucide-static
// release. Adding an icon is one line in ICONS, then `bun scripts/vendor-lucide.ts`.
// It rewrites web/vendor/lucide/*.svg (used by CSS masks) and the data block in
// web/icons.js (used by icon()). No icon is fetched at runtime.
import { readFileSync, writeFileSync } from "node:fs";

const VERSION = "1.64.0";
// Upstream renames: our stable name -> lucide-static file name.
const ALIASES: Record<string, string> = { "circle-help": "circle-question-mark", "more-horizontal": "ellipsis", "loader-circle": "loader-circle" };
export const ICONS = [
  // Navigation and structure
  "activity", "arrow-left", "arrow-right", "arrow-up-right", "chevron-down", "chevron-right", "chevron-left", "chevron-up", "menu", "x",
  "layers", "layout-grid", "list", "workflow", "route", "git-branch", "git-pull-request", "git-commit-horizontal", "hash", "link", "external-link",
  // Objects
  "bot", "brain", "calendar", "clock", "cloud", "code", "copy", "database", "file-text", "files", "folder", "globe", "key-round",
  "mail", "plug", "plug-zap", "search", "settings-2", "share-2", "shield-check", "terminal", "users", "user", "user-plus", "inbox", "bookmark", "tag",
  "message-square", "notebook-pen", "history", "archive", "download", "upload", "credit-card", "log-out", "log-in", "lock", "unlock",
  // State and feedback
  "check", "check-check", "circle-check", "circle-dashed", "circle-dot", "circle-help", "circle-x", "circle-alert", "triangle-alert", "info",
  "loader-circle", "refresh-cw", "rotate-ccw", "eye", "eye-off", "ellipsis", "more-horizontal", "plus", "minus", "trash-2", "pencil",
  "sparkles", "zap", "radio", "wifi-off", "pause", "play", "filter", "sliders-horizontal", "arrow-down-up", "sun", "moon",
  // App shell (Supabase-style top bar, rail, palette)
  "chevrons-up-down", "book-open", "command", "life-buoy", "circle-user", "panel-left", "bell", "keyboard", "corner-down-left", "arrow-up", "arrow-down", "house", "circle-play", "megaphone", "badge-check",
];

const tagPattern = /<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g;
const attributePattern = /([a-zA-Z][a-zA-Z0-9:-]*)="([^"]*)"/g;

async function fetchIcon(name: string) {
  const file = ALIASES[name] ?? name;
  const response = await fetch(`https://unpkg.com/lucide-static@${VERSION}/icons/${file}.svg`);
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  const svg = await response.text();
  if (!svg.includes("<svg") || /<script|on[a-z]+=/i.test(svg)) throw new Error(`${name}: unexpected content`);
  const nodes: [string, Record<string, string>][] = [];
  for (const [, tag, attrs] of svg.matchAll(tagPattern)) {
    const properties: Record<string, string> = {};
    for (const [, key, value] of attrs.matchAll(attributePattern)) properties[key] = value;
    nodes.push([tag, properties]);
  }
  if (!nodes.length) throw new Error(`${name}: no shapes`);
  const clean = svg.replace(/<!--[\s\S]*?-->/g, "").replace(/\s+class="[^"]*"/, "").trim() + "\n";
  return { name, nodes, clean };
}

if (import.meta.main) {
  const results = [];
  for (const name of [...new Set(ICONS)].sort()) results.push(await fetchIcon(name));
  const dir = new URL("../web/vendor/lucide/", import.meta.url);
  for (const { name, clean } of results) writeFileSync(new URL(`${name}.svg`, dir), clean);
  const iconsPath = new URL("../web/icons.js", import.meta.url);
  const source = readFileSync(iconsPath, "utf8");
  const block = `const icons = {\n${results.map(({ name, nodes }) => `  ${JSON.stringify(name)}: ${JSON.stringify(nodes)},`).join("\n")}\n};`;
  const next = source.replace(/const icons = \{[\s\S]*?\n\};/, block)
    .replace(/^\/\/ Lucide local icon subset\..*$/m, `// Lucide local icon subset (lucide-static ${VERSION}). ISC license; Feather-derived icons are MIT.`);
  writeFileSync(iconsPath, next);
  const cssPath = new URL("../web/design-system.css", import.meta.url);
  const rules = results.map(({ name }) => `.ds-icon[data-icon='${name}'] { --icon: url('/vendor/lucide/${name}.svg'); }`).join("\n");
  writeFileSync(cssPath, readFileSync(cssPath, "utf8").replace(/\/\* lucide:css:start \*\/[\s\S]*?\/\* lucide:css:end \*\//, `/* lucide:css:start */\n${rules}\n/* lucide:css:end */`));
  const license = new URL("../web/vendor/LICENSE-lucide.txt", import.meta.url);
  writeFileSync(license, readFileSync(license, "utf8").replace(/^Source: .*$/m, `Source: https://unpkg.com/lucide-static@${VERSION}/icons/ (generated by scripts/vendor-lucide.ts)`).replace(/^Retrieved: .*$/m, `Retrieved: 2026-10-30`));
  console.log(`Vendored ${results.length} Lucide icons from lucide-static ${VERSION}.`);
}
